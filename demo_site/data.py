"""Условные данные демо-сайта. Повторяют структуру сайта ИРНИТУ, но не являются сведениями реальных ОП.

В данные заложены отклонения, на которых видны альтернативные сценарии ТЗ:
расхождение часов в УП (требует проверки), аннотация вместо программы практики (пропуск),
РПД нового шаблона (неизвестный шаблон), ФОС ГИА без раздела критериев (частично обработан),
битая ссылка (ошибка скачивания) и ОП без ссылки на КУГ (предупреждение).
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class Disc:
    index: str
    name: str
    sems: dict[int, tuple[int, int, int]]     # семестр → (лек, лаб, пр) часов за семестр
    exam: list[int] = field(default_factory=list)
    zach: list[int] = field(default_factory=list)
    zach_oc: list[int] = field(default_factory=list)
    kp: list[int] = field(default_factory=list)
    kr: list[int] = field(default_factory=list)
    topics: list[str] = field(default_factory=list)
    goal: str = ""
    competencies: list[str] = field(default_factory=lambda: ["УК-1", "ОПК-1"])
    template: str = "standard"                 # standard | new (неизвестный шаблон)

    def hours(self):
        aud = sum(sum(v) for v in self.sems.values())
        control = 36 * len(self.exam)
        sr_sem = {s: max(4, (sum(v) // 2 + 6) // 2 * 2) for s, v in self.sems.items()}
        plan = aud + sum(sr_sem.values()) + control
        extra = (-plan) % 36
        if extra:
            last = max(self.sems)
            sr_sem[last] += extra
        sr = sum(sr_sem.values())
        plan = aud + sr + control
        return {"aud": aud, "kont": aud, "sr": sr, "control": control, "plan": plan, "ze": plan // 36, "sr_sem": sr_sem}


